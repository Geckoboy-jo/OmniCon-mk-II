#!/usr/bin/env bash
# configure_oracle_db.sh — Install Oracle Database Free (XE) on an Oracle Linux 9 VM
# and create the omnicon app user + games table.
#
# Run on the Oracle Cloud VM as opc (or root) after provisioning:
#   scp -i ~/.ssh/omnicon_oracle_free cloud/configure_oracle_db.sh opc@<VM_IP>:~/
#   ssh -i ~/.ssh/omnicon_oracle_free opc@<VM_IP>
#   export ORACLE_APP_PASSWORD="STRONG_PASSWORD_HERE"
#   export ALLOWED_CIDR="<YOUR_CLIENT_IP>/32"   # e.g. 69.166.46.173/32
#   chmod +x ~/configure_oracle_db.sh
#   sudo -E bash ~/configure_oracle_db.sh

set -euo pipefail

: "${ORACLE_APP_PASSWORD:?Set ORACLE_APP_PASSWORD before running}"
: "${ALLOWED_CIDR:?Set ALLOWED_CIDR to your client IP/32}"

ORACLE_APP_USER="${ORACLE_APP_USER:-omnicon}"
ORACLE_SERVICE="${ORACLE_SERVICE:-XE}"
ORACLE_PORT="${ORACLE_PORT:-1521}"

echo "==> Installing Oracle Database Free (XE)..."
# Add Oracle yum repository
if [[ ! -f /etc/yum.repos.d/oracle-database-preinstall-21c.repo ]]; then
    dnf install -y oracle-database-preinstall-21c 2>/dev/null || true
fi
dnf install -y oracle-database-xe-21c 2>/dev/null || {
    # Try direct RPM from Oracle repo
    cat > /etc/yum.repos.d/oracle-database-free.repo << 'REPO'
[oracle-database-free]
name=Oracle Database Free
baseurl=https://yum.oracle.com/repo/OracleLinux/OL9/appstream/x86_64
enabled=1
gpgcheck=1
gpgkey=https://yum.oracle.com/RPM-GPG-KEY-oracle-ol9
REPO
    dnf install -y oracle-database-free-23c 2>/dev/null || \
    dnf install -y oracle-database-xe-21c
}

echo "==> Configuring Oracle XE..."
# Configure XE with a system password (interactive); use expect if available
ORACLE_SYS_PASS="${ORACLE_SYS_PASSWORD:-${ORACLE_APP_PASSWORD}}"

if command -v expect >/dev/null 2>&1; then
    expect << EOF
spawn /etc/init.d/oracle-xe-21c configure
expect "Specify a password"
send "${ORACLE_SYS_PASS}\r"
expect "Confirm the password"
send "${ORACLE_SYS_PASS}\r"
expect eof
EOF
else
    echo "${ORACLE_SYS_PASS}" | /etc/init.d/oracle-xe-21c configure || \
    /etc/init.d/oracle-xe-21c configure
fi

echo "==> Starting Oracle XE..."
systemctl enable oracle-xe-21c 2>/dev/null || true
/etc/init.d/oracle-xe-21c start || true

echo "==> Opening firewall for Oracle port ${ORACLE_PORT} from ${ALLOWED_CIDR}..."
firewall-cmd --permanent --add-rich-rule="rule family='ipv4' source address='${ALLOWED_CIDR}' port protocol='tcp' port='${ORACLE_PORT}' accept" 2>/dev/null || true
firewall-cmd --reload 2>/dev/null || true
# Also allow via iptables if firewalld is absent
iptables -I INPUT -p tcp --dport "${ORACLE_PORT}" -s "${ALLOWED_CIDR}" -j ACCEPT 2>/dev/null || true

echo "==> Creating omnicon app user..."
export ORACLE_SID=XE
export ORACLE_BASE=/opt/oracle
export ORACLE_HOME=/opt/oracle/product/21c/dbhomeXE

"${ORACLE_HOME}/bin/sqlplus" -s / as sysdba << SQL
-- Create app user with limited privileges (least-privilege)
BEGIN
  EXECUTE IMMEDIATE 'CREATE USER ${ORACLE_APP_USER} IDENTIFIED BY ''${ORACLE_APP_PASSWORD}''';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -1920 THEN RAISE; END IF;
END;
/
-- Revoke default excessive privileges, grant minimum needed
ALTER USER ${ORACLE_APP_USER} QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION TO ${ORACLE_APP_USER};
GRANT CREATE TABLE TO ${ORACLE_APP_USER};
GRANT CREATE SEQUENCE TO ${ORACLE_APP_USER};

-- Games table
BEGIN
  EXECUTE IMMEDIATE 'CREATE TABLE ${ORACLE_APP_USER}.GAMES (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255) NOT NULL,
    DOWNLOAD_URL CLOB,
    COVER_URL CLOB,
    SYSTEM_NAME VARCHAR2(255),
    STATUS VARCHAR2(32) DEFAULT ''remote'',
    LOCAL_PATH VARCHAR2(1024),
    SIZE_BYTES NUMBER DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_PLAYED TIMESTAMP
  )';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

-- B+ tree index on STATUS for efficient queue queries
BEGIN
  EXECUTE IMMEDIATE 'CREATE INDEX ${ORACLE_APP_USER}.IDX_GAMES_STATUS ON ${ORACLE_APP_USER}.GAMES(STATUS)';
EXCEPTION WHEN OTHERS THEN
  IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
COMMIT;
EXIT;
SQL

echo ""
echo "==> Oracle DB setup complete."
echo "    Host:     \$(hostname -I | awk '{print \$1}')"
echo "    Port:     ${ORACLE_PORT}"
echo "    Service:  ${ORACLE_SERVICE}"
echo "    App user: ${ORACLE_APP_USER}"
echo ""
echo "Add to your ~/.oci/omnicon_env:"
echo "  export ORACLE_APP_HOST=\"\$(hostname -I | awk '{print \$1}')\""
echo "  export ORACLE_APP_SERVICE=\"${ORACLE_SERVICE}\""
echo "  export ORACLE_APP_USER=\"${ORACLE_APP_USER}\""
echo "  export ORACLE_APP_PASSWORD=\"${ORACLE_APP_PASSWORD}\""
